add_heading('第二章  数据基础与频谱预测方法', level=1)

add_heading('2.1  噪声数据集构建', level=2)
add_heading('2.1.1  声学评价指标', level=3)
add_body('声压级（SPL, dB）是噪声度量的基本物理量。窄带频谱展示了声能沿频率轴的连续分布，完整反映了噪声的频率特征。总声压级（OASPL）通过全频带能量积分给出单一数值，是噪声评价的核心总体指标。A计权声压级模拟人耳对不同频率的敏感度差异进行加权，常用于产品噪声水平的合规标定。')

add_heading('2.1.2  变量体系', level=3)
add_body('数据集每条记录包含三类变量：')
add_body('（1）工况参数（3维）：反映系统运行状态的无量纲化参数，与风机转速、流量和压比相关。')
add_body('（2）结构参数：描述关键几何特征的参数，包括翅片间距、管径和排数等，是降噪优化的设计变量。')
add_body('（3）输出变量：20~5000 Hz范围内的窄带声压级频谱，频率分辨率4 Hz，共1246个频点。该频段是产品噪声的主要能量分布区间，也是人耳听觉的敏感区域。')

add_heading('2.1.3  数据预处理', level=3)
add_body('原始频谱覆盖0~10000 Hz（2501点，4 Hz间隔）。考虑到主要噪声能量集中在5000 Hz以下，将频谱截取为20~5000 Hz范围（原始索引5~1250），减少输出维度至1246点。输入参数采用Z-score标准化消除量纲差异。')

add_heading('2.1.4  数据划分', level=3)
add_body('数据集包含多种产品型号（mode, 4类）和结构类型（type, 13类）。为准确评估模型对各类工况的泛化能力，采用基于mode×type共52种物理组合的分层抽样：对每种组合按80/20比例独立划分训练和验证样本。单样本组合归入训练集以保证覆盖。最终训练集865条，验证集214条。')

add_heading('2.2  频谱预测模型设计', level=2)
add_heading('2.2.1  总体框架', level=3)
add_body('模型采用编码器-解码器结构：傅里叶特征编码器将低维输入映射到高维隐空间；解码器通过转置卷积逐步上采样重建频谱的空间结构。设计原则是充分共享参数以应对数据稀缺，同时通过嵌入机制保留工况差异化能力。')

add_heading('2.2.2  傅里叶特征编码器', level=3)
add_body('低维物理参数到高维频谱的映射具有挑战性——相近的输入可能对应差异显著的频谱。本文引入随机傅里叶特征映射，将3维输入通过随机投影和sin/cos变换显式映射到64维特征空间。编码器由三层全连接网络（64→128→256→256）叠加LayerNorm、GELU激活和Dropout（0.5/0.5/0.3）构成。傅里叶特征尺度取1.0，在训练稳定性和表达能力之间取得平衡。')

add_heading('2.2.3  转置卷积解码器', level=3)
add_body('解码器将256维隐层向量经全连接层扩展后，通过6层转置卷积逐级将序列长度16上采样至1024（16→32→64→128→256→512→1024）。每层采用核大小4、步长2的转置卷积实现2倍分辨率提升，引入残差连接改善深层梯度流动。归一化层采用InstanceNorm以消除小批量（batch_size=8）场景下BatchNorm统计量不稳定的问题。末端嵌入SE通道注意力模块（8个通道，压缩比为2），自适应学习各特征通道的重要性权重。')

add_heading('2.2.4  工况嵌入与架构精简', level=3)
add_body('本文将mode（4类）和type（13类）各自维护一个16维的可学习嵌入向量。嵌入向量在编码器输出端拼接，形成288维的条件表示送入解码器，使共享的解码网络能够根据不同的mode/type组合自适应调整其输出。')
add_body('模型设计的早期版本为每种mode-type组合分配独立的输出头（共52个）。但实验表明，在每种组合仅有约17条训练数据的情况下，52分支架构在训练约500轮后即达到过拟合极限（val_mse=5.42 dB²），之后性能持续恶化。本文将52个独立头合并为1个全局共享头，模型头参数量从6100万降至117万。865条训练数据共同优化同一个头，数据/参数比从0.14条/万参数提升至7.4条/万参数（提升约53倍），从根本上缓解了每个子任务数据不足的困境。')
add_body('表2-1  52分支与单共享头架构参数对比', bold=True)
add_body('               | 52分支        | 单共享头')
add_body('任务头数量      | 52个独立      | 1个共享')
add_body('头参数总量      | 6100万        | 117万')
add_body('每头训练数据    | ~17条         | 865条')
add_body('验证dB-MSE      | 5.42→7.0(过拟合) | 2.66(持续下降)')

add_heading('2.3  频谱感知的损失函数', level=2)
add_body('损失函数决定了模型从数据中学习的方向和重点。对于噪声频谱预测，理想的损失函数应：①在1246个频点上准确回归声压级值；②对高声压级区域（占噪声总能量的主要部分）给予更高关注；③保证输出频谱具有物理合理性——相邻频率声压级不应出现非物理的剧烈跳变。基于以上设计目标，本文提出了包含三个分量的损失函数。')

add_heading('2.3.1  多分辨率均方误差', level=3)
add_body('仅在原分辨率的逐点MSE，模型可能过度关注局部细节而忽视宽频能量分布趋势。本文通过平均池化将频谱下采样至2倍和4倍粗分辨率，在三个尺度上同时计算MSE，权重分别为1.0、0.3和0.1。粗尺度的损失引导模型优先学习宽频包络，细尺度的损失逐步精调局部结构——这一"先粗后细"的课程学习策略有助于模型更稳定地收敛。')

add_heading('2.3.2  声压域峰值加权', level=3)
add_body('dB域的MSE对所有频点等权处理。但工程上高声压级区域的预测精度远比低声压区域关键——峰值1 dB的误差对噪声总水平的影响远大于谷值1 dB。本文将预测值和目标值从dB域变换到线性声压比域（10^(dB/20)），在声压域计算MSE。声压比值与声能量成正比，高声压处的误差被自然放大：60 dB处1 dB误差的惩罚约为20 dB处的100倍。这种自适应加权机制不需要手动调节权重，自动聚焦于物理上更重要的峰值区域。')

add_heading('2.3.3  Sobolev梯度正则化', level=3)
add_body('物理上合理的声学频谱应具有平滑性——相邻频率处的声压级是连续变化的。引入一阶差分正则化：惩罚预测频谱沿频率轴的梯度与真实频谱梯度的差异（L_grad = MSE(∇p, ∇t)）。该约束有效抑制了模型在数据不足时产生的虚假高频振荡，使预测频谱更符合物理规律。最终的总损失为三者的加权和：L_total = 5.0×L_multiMSE + 2.0×L_peak + 3.0×L_grad。')

add_heading('2.4  训练策略与超参数', level=2)
add_body('采用AdamW优化器（lr=3×10⁻⁴, wd=1×10⁻³），余弦退火暖重启学习率调度（T₀=150, T_mult=2），前5个epoch线性预热。配合梯度累积（每2步更新，等效batch=16）和混合精度训练。引入EMA（decay=0.999）在验证阶段使用平滑权重。数据增强方面，对频谱施加加性噪声（σ=0.8 dB）、幅度缩放（±8%）、频率微移（±12 Hz）和随机平滑，并约束总声压级不变以保证增强的物理合理性。')

add_heading('2.5  本章小结', level=2)
add_body('本章系统阐述了从数据到模型再到训练策略的完整方法。核心设计包括：分层抽样保证数据分布；52→1的架构精简解决小样本过拟合；多分辨率、峰值加权和梯度正则化的联合损失设计引导模型学习物理合理的频谱。')


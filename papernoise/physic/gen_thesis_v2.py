add_heading('第二章  数据基础与频谱预测方法', level=1)

add_heading('2.1  空调换热器噪声机理与数据集', level=2)
add_heading('2.1.1  声学基础与评价指标', level=3)
add_body('声压级（SPL, dB）是衡量噪声强度的基本物理量。频谱描述了声能沿频率轴的分布，完整反映了噪声的物理特征。总声压级（OASPL）通过全频带能量积分给出单一数值，是噪声评价的核心指标。A计权声压级模拟人耳对不同频率的敏感度差异，常用于产品噪声水平的标定。在空调噪声分析中，宽带的湍流噪声和窄带的叶片通过频率（BPF）谐波具有不同的产生机理和频域特征。')

add_heading('2.1.2  数据来源与变量选择', level=3)
add_body('本数据集来源于多型号空调换热器在不同运行工况和结构配置下的模拟和测试。输入变量分为两类：')
add_body('（1）工况参数（3维）：反映风机运行状态的无量纲化参数，主要包括转速、流量和压比相关量，表征系统的工作点。')
add_body('（2）结构参数：换热器的关键几何设计参数，包括翅片间距——决定气流通道宽度和翅片表面边界层发展；管径——影响管后尾流区的宽度和涡脱落频率；换热器排数——决定气流流经的总距离和沿程压降。此外还包括翅片厚度、管间距等辅助几何参数。')
add_body('输出变量为20~5000 Hz频率范围内的声压级频谱，频率分辨率4 Hz，共1246个频点。该频段是空调噪声的主要能量分布区域。')

add_heading('2.1.3  数据预处理', level=3)
add_body('原始频谱覆盖0~10000 Hz（2501点）。考虑到空调气动噪声能量主要集中在5000 Hz以下，且人耳听觉敏感区为20~20000 Hz，本文将频率范围截取为20~5000 Hz（索引5~1250，1246点）。这一处理降低了输出维度，去除了对产品噪声评价贡献较小的高频段。输入参数采用Z-score标准化以消除量纲差异。')

add_heading('2.1.4  数据集划分策略', level=3)
add_body('空调产品存在多种型号（mode, 4类）和换热器类型（type, 13类）的差异，不同组合的噪声频谱特性可能有本质不同。为确保验证集能公平评估模型对各类工况的泛化能力，采用基于mode×type共52种物理组合的分层抽样：每种组合按80/20比例划分，样本数为1的组合归入训练集。最终数据集包含865条训练样本和214条验证样本。')

add_heading('2.1.5  数据特性初步分析', level=3)
add_body('对不同工况的频谱分析显示：不同mode下的频谱在峰值频率和宽频衰减率上呈现系统性差异；同一mode内不同type的频谱形状相似，主要表现为整体声压级的平移。这启示在设计模型时，可将频谱生成过程理解为"形状+幅值"的两阶段过程。')

add_heading('2.2  频谱预测模型设计与训练', level=2)
add_heading('2.2.1  模型总体框架', level=3)
add_body('模型采用编码器-解码器结构，将低维物理参数映射到高维频谱。具体流程为：傅里叶特征编码器将输入参数映射到隐空间；工况嵌入向量提供mode/type信息；共享解码器通过转置卷积逐步重建频谱；共享任务头输出最终的1246点频谱。设计原则是：通过充分的参数共享应对数据稀缺，通过嵌入机制保留工况差异化的能力。')

add_heading('2.2.2  傅里叶特征编码', level=3)
add_body('低维物理参数到高维频谱的映射具有挑战性——相近的输入可能对应差异显著的频谱。借鉴神经正切核理论，采用随机傅里叶特征映射将3维输入显式映射到64维空间（通过sin/cos变换），使编码器能学习更丰富的输入-输出关系。编码器由三层全连接网络构成，每层后接LayerNorm和GELU激活，并采用Dropout（0.5/0.5/0.3）进行正则化。')

add_heading('2.2.3  转置卷积解码与注意力', level=3)
add_body('解码器将256维隐层向量通过全连接层扩展后，经6层转置卷积逐级上采样（16→32→64→128→256→512→1024点），最后通过SE通道注意力机制自适应加权不同特征通道。归一化采用InstanceNorm以适应小批量场景（batch_size=8）。')

add_heading('2.2.4  工况嵌入与架构精简（核心设计）', level=3)
add_body('模型设计的早期版本为每种mode-type组合分配独立的任务头（共52个）。然而在1079条数据、52种组合的条件下，每种组合平均仅约17条训练样本。实验表明，52分支模型在训练约500轮后验证集精度即达顶点（val_mse=5.42 dB²），随后迅速恶化——呈现典型的过拟合。')
add_body('为解决这一根本矛盾，本文进行了架构精简：将52个独立任务头合并为1个全局共享头。与此同时，引入可学习的mode嵌入和type嵌入（各16维），在编码器输出端拼接后送入解码器，使得共享的解码器和头能够根据工况信息自适应调节输出。精简后模型总参数从6100万降至164万。更重要的是，865条训练数据共同训练一个头，数据/参数比从0.14条/万参数提升至7.4条/万参数。')
add_body('表2-1  52分支与单共享头架构对比', bold=True)
add_body('               | 52分支架构        | 单共享头架构')
add_body('头数量          | 52个独立         | 1个共享')
add_body('头参数总量      | 6100万           | 117万')
add_body('每头训练数据    | ~17条            | 865条')
add_body('验证dB-MSE      | 5.42(过拟合)     | 2.66(持续下降)')

add_heading('2.2.5  训练策略配置', level=3)
add_body('采用AdamW优化器，初始学习率3×10⁻⁴，权重衰减1×10⁻³。学习率采用余弦退火暖重启策略（T₀=150 epoch），前5个epoch进行线性预热。配合梯度累积（每2步更新，等效batch=16）和混合精度训练加速计算。引入指数移动平均（EMA, decay=0.999）提升验证集泛化性能。数据增强方面，对频谱施加加性噪声（σ=0.8 dB）、幅度缩放（±8%）、频率微移（±12 Hz）和随机平滑，并约束总声压级不变以保持物理合理性。')

add_heading('2.3  频谱感知的损失函数设计', level=2)
add_body('损失函数决定了模型从数据中学习什么。对于噪声频谱预测，理想的损失函数应满足：①鼓励逐点声压级精度的回归；②对高声压级区域（对总噪声贡献大）给予更多关注；③约束频谱满足物理平滑性（相邻频点声压级不应剧烈跳变）。基于这些工程需求，本文设计了包含三个分量的损失函数。')

add_heading('2.3.1  多分辨率均方误差', level=3)
add_body('仅在原分辨率（4 Hz间隔）计算MSE，模型可能倾向于过度关注局部细节而忽视宽频趋势。本文引入多分辨率MSE：通过平均池化将频谱下采样至2倍和4倍粗分辨率，在三个尺度上同时计算MSE，权重分别为1.0、0.3和0.1。这一设计体现了"先粗后细"的思路——粗尺度损失引导模型优先捕捉频谱的整体形状，细尺度损失再逐步精调局部结构。')

add_heading('2.3.2  声压域峰值加权约束', level=3)
add_body('dB域的MSE对各频点等权处理，但工程上高声压级区域的预测精度远比低声压区域重要——峰值误差对OASPL和主观响度的影响大得多。本文将预测和目标频谱从dB域转换到线性声压比域（通过10^(dB/20)变换），在声压域计算MSE。由于声压比值与声能量成正比，高声压级处的误差被自然放大（60 dB处1 dB误差的惩罚约为20 dB处的100倍），实现了无需手工调参的自适应峰值关注。')

add_heading('2.3.3  Sobolev一阶梯度正则化', level=3)
add_body('物理上合理的声学频谱应具有平滑性——相邻频率的声压级是连续变化的，不应出现非物理的锯齿状振荡。本文引入一阶差分正则化：惩罚预测频谱沿频率轴的梯度与真实频谱梯度的差异。这一约束有效抑制了模型在训练数据不足时产生的虚假高频波动，使预测频谱更加符合物理规律。')
add_body('最终损失函数为三者的加权和：L = 5.0×多分辨率MSE + 2.0×峰值约束 + 3.0×梯度正则化。权重经消融实验确定。')

add_heading('2.4  本章小结', level=2)
add_body('本章以"数据→模型→损失→训练"为主线，系统阐述了空调换热器噪声频谱预测方法的构建过程。核心设计包括：通过分层抽样保证数据代表性；通过架构精简（52→1头）和工况嵌入解决小样本过拟合；通过多分辨率和声压域变换提升损失函数的物理合理性。')


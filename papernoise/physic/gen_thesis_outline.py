add_heading('2.3  频谱感知的多目标损失函数', level=2)
add_body('声学频谱预测对损失函数的设计有特殊要求：①需要同时在1246个频点上精确回归dB值；②频谱的峰值区域（高声压频段）对总噪声水平的贡献远大于谷值区域，需给予更高权重；③物理上合理的频谱应具有平滑性——相邻频率的声压级不应出现剧烈跳变。基于上述考虑，本文设计了包含三个分量的频谱感知损失函数。')

add_heading('2.3.1  多分辨率MSE（课程学习策略）', level=3)
add_body('单一分辨率的逐点MSE仅关注最细粒度的频谱结构，可能导致模型在早期训练阶段过度关注局部细节而忽略宽带趋势。本文引入多分辨率MSE：除原分辨率（1246点，4 Hz间隔）外，通过对频谱进行2倍和4倍平均池化下采样，在粗尺度上施加额外的MSE约束。粗尺度的损失引导模型优先学习频谱的宏观包络（宽带噪声的能量分布趋势），细尺度的损失再逐步精调共振峰和窄带特征的位置与幅值。三种分辨率的损失权重分别为1.0（原分辨率）、0.3（2倍下采样）和0.1（4倍下采样），体现了"先粗后细、粗主细辅"的课程学习理念。')

add_heading('2.3.2  线性域峰值约束', level=3)
add_body('dB域的MSE对各频率点的一视同仁存在一个问题：高频段或低声压级的预测误差与高声压级的预测误差被同等对待，但后者对OASPL和主观响度的影响要大得多。本文设计线性域峰值约束来弥补这一不足：将预测和目标频谱从dB域转换到线性声压比域（通过10^(dB/20)），在线性域计算MSE。由于线性域数值与声压成正比，高声压级的误差被自然放大——60 dB处1 dB误差在线性域的惩罚约为115，而20 dB处仅为1.2，权重差异约100:1。这种自适应加权机制不需要额外的手工权重参数，使模型自然地聚焦于物理上更重要的峰值区域。')

add_heading('2.3.3  Sobolev一阶梯度正则化', level=3)
add_body('Sobolev损失通过惩罚预测频谱一阶差分与目标频谱一阶差分之间的差异，显式约束频谱的平滑性。形式为：L_grad = MSE(∇p, ∇t)，其中∇为沿频率轴的一阶差分算子。这一约束有两个物理动机：①真实物理频谱的相邻频率之间存在连续性，不应出现非物理的剧烈振荡；②梯度正则化作为一种谱方法，能有效抑制模型在训练数据不足时对噪声的过拟合。梯度正则化仅作用于原分辨率频谱，不进行多尺度扩展——因为不同分辨率下的梯度具有不同的物理含义。')

add_heading('2.3.4  损失权重配置与总损失表达式', level=3)
add_body('综合以上三个分量的总损失函数为：')
add_body('  L_total = 5.0 × L_multiMSE + 2.0 × L_linearPeak + 3.0 × L_sobolev')
add_body('权重配置遵循以下原则：多分辨率MSE为核心损失（权重5.0），提供主要的逐点回归梯度；Sobolev正则化次之（权重3.0），保证频谱平滑性；线性峰值约束辅助（权重2.0），强化峰值区域精度。这一配置经过多轮消融实验验证，在训练稳定性和最终验证集精度之间取得了良好平衡。')


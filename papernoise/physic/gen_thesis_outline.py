add_heading('2.1  空调噪声机理与数据集', level=2)
add_heading('2.1.1  声压级、频谱与评价指标', level=3)
add_body('声压级（Sound Pressure Level, SPL）是衡量噪声强度的核心物理量，定义为声压有效值与参考声压之比的对数值。频谱表示不同频率成分的声压级分布，是噪声分析和控制的基础。常用的噪声评价指标包括：总声压级（OASPL），通过对全频带声压进行能量求和获得；倍频程频谱，按对数频率间隔分段求和；A计权声压级，模拟人耳对不同频率的敏感度差异进行加权。')
add_body('在空调噪声分析中，频谱中的宽带成分（气流湍流噪声）和窄带峰值（旋转机械的叶片通过频率及其谐波）反映了不同的物理产生机制，需要模型具备同时捕获宏观趋势和局部细节的能力。')

add_heading('2.1.2  数据来源与变量体系', level=3)
add_body('本文数据集来源于空调系统在不同运行工况和结构配置下的数值模拟或实验测量结果。每条数据记录包含以下变量：')
add_body('（1）工况参数（3维）：描述了风机的运行状态，包括风机转速（RPM）、空气流量等反映系统工作点的无量纲参数。这些参数决定了气流的基本流动状态和噪声的基线水平。')
add_body('（2）结构参数（n维）：描述了换热器和风道的几何特征，包括但不限于翅片间距——影响气流通道的阻塞程度和涡脱落频率；管径——影响换热器迎风面的流动阻力；排数——影响气流流经换热器的距离和压降；以及翅片厚度、管间距等其他几何参数。这些参数共同决定了气流流动的边界条件，是降噪优化的关键设计变量。')
add_body('（3）输出变量：目标频谱为20~5000 Hz频率范围内的声压级分布，频率分辨率为4 Hz，共1246个频点。该频段覆盖了空调噪声的主要能量分布范围，同时去除了高频段的无效噪声。')

add_heading('2.1.3  频谱预处理与频段选择', level=3)
add_body('原始频谱覆盖0~10000 Hz范围（2501点，4 Hz间隔）。考虑到：①空调气动噪声的主要能量集中在5000 Hz以下；②人耳听觉的敏感区域为20~20000 Hz；③高频段数据信噪比较低，本文截取20~5000 Hz频段（对应原始频谱索引5~1250，共1246点）作为预测目标。此举有效降低了模型输出维度，减少了高频噪声对训练过程的干扰，同时保证了工程应用所需的频段覆盖。')

add_heading('2.1.4  分层抽样与数据划分', level=3)
add_body('由于不同空调型号（mode）和换热器类型（type）的频谱特性差异显著，随机划分可能导致验证集中某些工况组合的样本缺失。本文采用基于物理工况组合的分层抽样策略：将mode和type的笛卡尔积作为52种物理工况组合，对每种组合按照80/20比例独立抽取训练和验证样本。对于样本数为1的组合，全部归入训练集以保证每种工况均有训练覆盖。该策略确保了训练集和验证集在物理工况层面具有一致的数据分布。')

add_heading('2.1.5  数据特性与参数-频谱关联分析', level=3)
add_body('对数据集的初步分析表明：不同mode条件下，频谱的整体形态（峰值频率、高频率衰减率）呈现系统性差异；同一mode内不同type的频谱形状较为相似，主要表现在整体声压级的平移。这一观察启示我们：模型设计时可将频谱生成过程解耦为"频谱形状生成"和"整体幅值调整"两个阶段，前者由type主导，后者可由mode信息调控。')

add_heading('2.2  频谱预测模型设计', level=2)
add_heading('2.2.1  总体编码-解码框架', level=3)
add_body('模型采用编码器-解码器架构，由四个核心组件构成：傅里叶特征编码器将低维工况参数映射到高维特征空间；共享解码器通过转置卷积逐层恢复频谱的空间分辨率；工况嵌入注入模块将mode和type信息融合到解码过程；共享任务头最终输出1246点的预测频谱。模型的输入为工况参数和结构参数的拼接向量，输出为对应条件下的完整频谱。')

add_heading('2.2.2  傅里叶特征编码器', level=3)
add_body('低维物理参数到高维频谱的映射是一类典型的"坐标到函数"回归问题。标准的全连接编码器对低维输入的表征能力有限——相似的输入可能产生差异不显著的隐层表示。傅里叶特征映射通过随机投影和正弦/余弦变换，将3维输入映射到64维的傅里叶特征空间，使得编码器能够学习到更丰富的频谱变化模式。映射公式为：γ(x) = [sin(2πBx), cos(2πBx)]，其中B为服从高斯分布的随机矩阵。经过分析，本文采用尺度参数为1.0的温和映射，避免高频傅里叶特征在平滑物理函数上的过度振荡。编码器由三层全连接网络构成（64→128→256→256），每层后接LayerNorm、GELU激活和Dropout正则化。')

add_heading('2.2.3  共享解码器与多分辨率上采样', level=3)
add_body('解码器从256维隐层向量出发，通过6层转置卷积逐步将16点的初始序列上采样至1024点。每层采用核大小为4、步长为2的转置卷积实现2倍分辨率提升，并引入残差连接以改善深层梯度传播。归一化层采用InstanceNorm以消除小批量（batch_size=8）场景下BatchNorm统计量不稳定的问题。解码器末端嵌入SE通道注意力模块，通过全局平均池化→降维→激活→升维→Sigmoid的瓶颈结构，自适应学习8个特征通道的重要性权重。最终输出为[B, 8, 1024]的中间特征表示。')

add_heading('2.2.4  工况嵌入注入机制', level=3)
add_body('为使解码器感知当前生成目标所属的物理工况（哪种mode和type），本文引入可学习的工况嵌入向量。mode（4类）和type（13类）各自维护一个16维的嵌入表。在编码器输出端，将mode嵌入和type嵌入与隐层向量拼接，形成[B, 288]的条件表示，再送入解码器。这一设计使得共享解码器能够根据不同的mode/type组合调整其内部表示，实现了"参数共享下的条件差异化生成"。')

add_heading('2.2.5  架构演进：52分支→单共享头', level=3)
add_body('（1）过拟合诊断。本文模型的早期版本为每个mode-type组合分配独立的任务头（共52个），每个头包含约117万参数。然而，1079条总数据在52种组合上的平均分配仅为每头约17条训练样本。实验显示，52分支版本在训练约500轮后val_mse达到5.42 dB²的最低点，之后迅速反弹至7.0 dB²以上——呈现出典型的小样本过拟合特征：模型记住了训练集中的个别样本，却无法泛化到同组合下的新样本。类似地，52分支的多个历史版本均在早期达到最优后持续恶化。')
add_body('（2）分支合并与参数效率分析。为解决这一根本矛盾，本文将52个独立任务头合并为一个全局共享头。合并后，所有865条训练数据共同训练一个117万参数的头，数据/参数比从0.14条/万参数提升至7.4条/万参数（提升53倍）。表2-1对此进行了对比。')
